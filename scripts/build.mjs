import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const endpoint = process.env.BUGSHIELD_ENDPOINT || 'https://multiagentnew.onrender.com/sdk/bugshield.js';
const key = process.env.BUGSHIELD_KEY || '';
const commit = process.env.RENDER_GIT_COMMIT || 'local';

fs.writeFileSync(path.join(root, 'config.js'),
  `// Generated by scripts/build.mjs — do not edit.\n` +
  `window.BUGSHIELD_ENDPOINT = ${JSON.stringify(endpoint)};\n` +
  `window.BUGSHIELD_KEY = ${JSON.stringify(key)};\n` +
  `window.BUGSHIELD_BUILD_INFO = { commit: ${JSON.stringify(commit)} };\n`);

fs.writeFileSync(path.join(root, 'version.json'), JSON.stringify({
  commit, service: 'amazin-demo-shop', generated: new Date().toISOString(),
}, null, 2) + '\n');

console.log('[build] wrote config.js and version.json for', commit);
